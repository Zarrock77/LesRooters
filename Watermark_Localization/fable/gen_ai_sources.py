"""Build AI-looking clean source banks (the competition images are AI-generated; COCO photos are not).

  vae    : every COCO source passed through a latent-diffusion VAE (encode -> decode): same content, AI texture
  sdxl   : fresh 512x512 images generated by SDXL-Turbo from COCO captions
Runs in Fable's own environment (venv_gen). No official competition image is read.
Output: <out>/clean.npy [N,512,512,3] uint8.
"""
import argparse
import json
from pathlib import Path

import numpy as np
import torch

ap = argparse.ArgumentParser()
ap.add_argument("--mode", required=True, choices=["vae", "sdxl", "regen"])
ap.add_argument("--src", type=Path, help="clean.npy to regenerate (regen mode); writes regen.npy next to it")
ap.add_argument("--strength", type=float, default=0.5)
ap.add_argument("--out", required=True, type=Path)
ap.add_argument("--coco", type=Path, help="clean.npy of the COCO bank (vae mode)")
ap.add_argument("--captions", type=Path, help="captions_val2017.json (sdxl mode)")
ap.add_argument("--count", type=int, default=4000)
ap.add_argument("--steps", type=int, default=2)
args = ap.parse_args()
args.out.mkdir(parents=True, exist_ok=True)
torch.backends.cuda.matmul.allow_tf32 = True

if args.mode == "regen":
    # Same picture re-synthesised by a diffusion model (image-to-image): what an edited/inpainted/outpainted
    # region looks like next to untouched pixels. Index-aligned with the source bank.
    from diffusers import AutoPipelineForImage2Image
    pipe = AutoPipelineForImage2Image.from_pretrained("stabilityai/sdxl-turbo", torch_dtype=torch.float16, variant="fp16").to("cuda")
    pipe.set_progress_bar_config(disable=True)
    src = np.load(args.src, mmap_mode="r")
    n = min(len(src), args.count)
    regen = np.lib.format.open_memmap(args.out / "regen.npy", mode="w+", dtype=np.uint8, shape=(len(src), 512, 512, 3))
    generator = torch.Generator("cuda").manual_seed(20261122)
    rng = np.random.default_rng(20261122)
    for s in range(0, n, 16):
        batch = torch.from_numpy(np.array(src[s:s + 16])).permute(0, 3, 1, 2).float().div(255).cuda()
        strength = float(rng.choice([0.34, 0.5, 0.5, 0.67]))
        images = pipe(prompt=[""] * len(batch), image=batch, strength=strength, num_inference_steps=3, guidance_scale=0.0,
                      generator=generator, output_type="np").images
        regen[s:s + len(batch)] = (np.clip(images, 0, 1) * 255).round().astype(np.uint8)
        if s % 320 == 0:
            print("REGEN", s, "/", n, strength, flush=True)
    regen.flush()
    (args.out / "REGEN_DONE").write_text(str(n))
    print("REGEN_DONE", n, flush=True)
    raise SystemExit(0)

if args.mode == "vae":
    from diffusers import AutoencoderKL
    vae = AutoencoderKL.from_pretrained("madebyollin/sdxl-vae-fp16-fix", torch_dtype=torch.float16).cuda().eval()
    src = np.load(args.coco, mmap_mode="r")
    n = min(len(src), args.count)
    clean = np.lib.format.open_memmap(args.out / "clean.npy", mode="w+", dtype=np.uint8, shape=(n, 512, 512, 3))
    with torch.no_grad():
        for s in range(0, n, 32):
            x = torch.from_numpy(np.array(src[s:s + 32])).cuda().permute(0, 3, 1, 2).half() / 127.5 - 1
            y = vae.decode(vae.encode(x).latent_dist.mode()).sample
            clean[s:s + 32] = ((y.float().clamp(-1, 1) + 1) * 127.5).round().byte().permute(0, 2, 3, 1).cpu().numpy()
            if s % 640 == 0:
                print("VAE", s, "/", n, flush=True)
else:
    from diffusers import AutoPipelineForText2Image
    pipe = AutoPipelineForText2Image.from_pretrained("stabilityai/sdxl-turbo", torch_dtype=torch.float16, variant="fp16").to("cuda")
    pipe.set_progress_bar_config(disable=True)
    captions = [a["caption"].strip() for a in json.loads(args.captions.read_text())["annotations"]]
    rng = np.random.default_rng(20261121)
    rng.shuffle(captions)
    styles = ["", "photo, ", "high quality photograph, ", "detailed realistic photo, ", "professional photography, "]
    n = args.count
    clean = np.lib.format.open_memmap(args.out / "clean.npy", mode="w+", dtype=np.uint8, shape=(n, 512, 512, 3))
    generator = torch.Generator("cuda").manual_seed(20261121)
    for s in range(0, n, 16):
        prompts = [styles[int(rng.integers(len(styles)))] + captions[(s + k) % len(captions)] for k in range(min(16, n - s))]
        images = pipe(prompt=prompts, num_inference_steps=args.steps, guidance_scale=0.0, height=512, width=512,
                      generator=generator, output_type="np").images
        clean[s:s + len(prompts)] = (np.clip(images, 0, 1) * 255).round().astype(np.uint8)
        if s % 320 == 0:
            print("SDXL", s, "/", n, flush=True)
clean.flush()
(args.out / "SOURCES_DONE").write_text(str(len(clean)))
print("AI_SOURCES_DONE", args.mode, len(clean), flush=True)
